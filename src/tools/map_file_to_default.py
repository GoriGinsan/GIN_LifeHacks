"""Make an expression map saved by GIN Pad life hack the map that new installations start with.

Usage:  python map_file_to_default.py <game>/UserData/GIN/Pad/expression-map.txt
        [--output src/Pad/DefaultExpressionMap.cs]

The file holds one pose per line (eyes / mouth / brows, in map order) as "shape=weight" pairs;
the teeth weight of a mouth pose is "#teeth". The poses are written unchanged, in the same order,
into DefaultExpressionMap.cs. (src/tools/learn_expression_map.py learns a map from scenes instead.)
"""
from pathlib import Path
import argparse

TEETH = '#teeth'


def read(path):
    stops = {'eyes': [], 'mouth': [], 'brows': []}
    for line in Path(path).read_text(encoding='utf-8-sig').splitlines():
        parts = line.split('\t')
        if parts[0] not in stops:
            continue   # comment or blank line
        pose = {}
        for part in parts[1:]:
            name, _, weight = part.rpartition('=')
            if name:
                pose[name] = float(weight)
        stops[parts[0]].append(pose)
    return stops


def names_of(poses, skip=()):
    names = []
    for pose in poses:
        for name in pose:
            if name not in names and name not in skip:
                names.append(name)
    return names


def number(value):
    return ('%.2f' % value).rstrip('0').rstrip('.') + 'f'


def rows(poses, names):
    return '\n'.join('            new float[] { ' + ', '.join(number(pose.get(name, 0.0)) for name in names) + ' },' for pose in poses)


def quoted(names):
    return ', '.join('"%s"' % name for name in names)


TEMPLATE = """// Generated by src/tools/map_file_to_default.py from the author's own expression map
// (%(source)s, made with the Map tab's pose editor). Do not edit by hand: run the tool again.
//
// Weights are KKPE Blend Shape weights (0-100); a shape a pose does not name is 0 there.
namespace GinPadHack
{
    internal static class DefaultExpressionMap
    {
        // Rows of the map, top to bottom.
        internal static readonly string[] EyeShapes = { %(eye_names)s };
        internal static readonly float[][] Eyes =
        {
%(eyes)s
        };

        // Columns of the map, left to right.
        // Teeth: weight of the single teeth row (Blend Shape 29 of cf_O_tooth) for each column.
        internal static readonly string[] MouthShapes = { %(mouth_names)s };
        internal static readonly float[][] Mouths =
        {
%(mouths)s
        };
        internal static readonly float[] Teeth = { %(teeth)s };

        // Brow strip under the map, left to right.
        internal static readonly string[] BrowShapes = { %(brow_names)s };
        internal static readonly float[][] Brows =
        {
%(brows)s
        };
    }
}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('map', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parent.parent / 'Pad' / 'DefaultExpressionMap.cs')
    args = parser.parse_args()

    stops = read(args.map)
    eye_names = names_of(stops['eyes'])
    mouth_names = names_of(stops['mouth'], skip=(TEETH,))
    brow_names = names_of(stops['brows'])
    args.output.write_text(TEMPLATE % {
        'source': 'UserData/GIN/Pad/' + args.map.name,
        'eye_names': quoted(eye_names), 'eyes': rows(stops['eyes'], eye_names),
        'mouth_names': quoted(mouth_names), 'mouths': rows(stops['mouth'], mouth_names),
        'teeth': ', '.join(number(pose.get(TEETH, 0.0)) for pose in stops['mouth']),
        'brow_names': quoted(brow_names), 'brows': rows(stops['brows'], brow_names),
    }, encoding='utf-8', newline='\n')
    print('%s: %d eye rows, %d mouth columns, %d brow poses' % (args.output.name, len(stops['eyes']), len(stops['mouth']), len(stops['brows'])))


if __name__ == '__main__':
    main()
