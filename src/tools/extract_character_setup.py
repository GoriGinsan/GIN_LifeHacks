"""Turn a Studio scene that shows one set-up character into the Char Setup template.

Usage:  python extract_character_setup.py setup-scene.png --kkib <KK in Blender folder>
        [--output src/Timeline/CharacterSetup.xml]

The scene must hold exactly one character. Everything around it becomes the template:

  * objects attached to the character's accessory points (items, folders and their children)
    and objects beside it (same parent in the workspace), with their local position, rotation,
    scale, colours, visibility and Material Editor settings;
  * NodesConstraints links between those objects;
  * every Timeline row of the character or of those objects, in the scene's group order and
    with the scene's row colours.

Rows of the character name bones by their transform name (the path is resolved on each
character). The body mesh's single Blend Shape rows become one "every shape" row that keeps
the scene's order. The scene is read with KK in Blender's reader (src/kkib_native).
"""
from pathlib import Path
import argparse
import importlib
import sys
import types
import xml.etree.ElementTree as ET

BODY_RENDERER = 'o_body_a'
ME_GUID = 'com.deathweasel.bepinex.materialeditor'


def load_reader(kkib):
    package = types.ModuleType('_kkib_native')
    package.__path__ = [str(Path(kkib) / 'src' / 'kkib_native')]
    sys.modules['_kkib_native'] = package
    return (importlib.import_module('_kkib_native.studio_scene'),
            importlib.import_module('_kkib_native.cards'),
            importlib.import_module('_kkib_native.studio_nodes_constraints'))


def numbers(values, digits=7):
    return ' '.join(('%.' + str(digits) + 'g') % v for v in values)


def colour(c):
    return numbers((c['r'], c['g'], c['b'], c['a']), 6)


def unpack(cards, value):
    if isinstance(value, (bytes, bytearray)):
        return cards.unpack(bytes(value))
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('scene', type=Path)
    parser.add_argument('--kkib', type=Path, required=True, help='KK in Blender folder (scene reader)')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'Timeline' / 'CharacterSetup.xml')
    args = parser.parse_args()

    scene_mod, cards, links_mod = load_reader(args.kkib)
    data = args.scene.read_bytes()
    scene = scene_mod.parse(data)
    reader = scene_mod.Reader(data, len(data) - scene['trailing_bytes'])
    assert reader.string() == 'KKEx', 'no extended data in the scene'
    reader.i32()
    extended = cards.unpack(reader.take(reader.count(scene_mod.MAX_BYTES)))

    walked = scene_mod.walk(scene)
    by_key = {obj['key']: obj for obj, _ in walked}
    parent_of = {obj['key']: parent for obj, parent in walked}
    characters = [obj for obj, _ in walked if obj['kind'] == 'character']
    assert len(characters) == 1, 'the setup scene must hold exactly one character'
    character = characters[0]
    order = sorted(by_key)                       # Timeline objectIndex = rank of the key

    # Sideloader: original mod GUID and slot of every modded item
    mods = {}
    for raw in extended['com.bepis.sideloader.universalautoresolver'][1].get('itemInfo', []):
        info = unpack(cards, raw)
        mods[info['SceneDicKey']] = info['ModID']

    # Material Editor settings by object key
    material = {}
    me = extended.get(ME_GUID, [0, {}])[1]
    for list_name, tag in (('RendererPropertyList', 'renderer'), ('MaterialShaderList', 'shader'),
                           ('MaterialFloatPropertyList', 'float'), ('MaterialColorPropertyList', 'color')):
        for raw in unpack(cards, me.get(list_name)) or []:
            entry = unpack(cards, raw)
            material.setdefault(entry['ID'], []).append((tag, entry))

    template = ET.Element('characterSetup', source=args.scene.name)
    template.append(ET.Comment(' Generated by src/tools/extract_character_setup.py; regenerate instead of editing by hand. '))
    objects = ET.SubElement(template, 'objects')
    setup_keys = set()

    def add_object(parent_element, obj, point):
        setup_keys.add(obj['key'])
        attributes = {'id': 'k%d' % obj['key']}
        if point is not None:
            attributes['point'] = str(point)
        attributes.update(position=numbers(obj['position']), rotation=numbers(obj['rotation']), scale=numbers(obj['scale']))
        if obj['kind'] == 'folder':
            element = ET.SubElement(parent_element, 'folder', name=obj['name'], **attributes)
        else:
            attributes.update(group=str(obj['group']), category=str(obj['category']), no=str(obj['no']))
            if obj['key'] in mods:
                attributes['mod'] = mods[obj['key']]
            attributes.update(visible='1' if obj['visible'] else '0', alpha=numbers([obj['alpha']], 6),
                              colors='|'.join(colour(c) for c in obj['colors']),
                              lineColor=colour(obj['line_color']), lineWidth=numbers([obj['line_width']], 6),
                              emissionColor=colour(obj['emission_color']), emissionPower=numbers([obj['emission_power']], 6),
                              lightCancel=numbers([obj['light_cancel']], 6))
            element = ET.SubElement(parent_element, 'item', **attributes)
            for tag, entry in material.get(obj['key'], []):
                if tag == 'renderer':
                    ET.SubElement(element, 'renderer', name=entry['RendererName'], property=str(entry['Property']), value=str(entry['Value']))
                elif tag == 'shader':
                    shader = {'material': entry['MaterialName'], 'queue': str(entry['RenderQueue'])}
                    if entry.get('ShaderName'):
                        shader['shader'] = entry['ShaderName']
                    ET.SubElement(element, 'shader', **shader)
                elif tag == 'float':
                    ET.SubElement(element, 'float', material=entry['MaterialName'], property=entry['Property'], value=str(entry['Value']))
                else:
                    ET.SubElement(element, 'color', material=entry['MaterialName'], property=entry['Property'], value=numbers(entry['Value'], 6))
        for child in obj.get('children') or []:
            add_object(element, child, None)

    for point, items in sorted(character['children'].items()):
        for obj in items:
            add_object(objects, obj, point)
    for obj, parent in walked:
        if obj is not character and parent == parent_of[character['key']] and parent_of.get(obj['key']) == parent_of[character['key']]:
            add_object(objects, obj, 'beside')

    # NodesConstraints links between setup objects
    for link in links_mod.from_extended(extended, scene):
        if link['parent_key'] in setup_keys and link['child_key'] in setup_keys and not link['parent_path'] and not link['child_path']:
            ET.SubElement(template, 'constraint', parent='k%d' % link['parent_key'], child='k%d' % link['child_key'],
                          enabled='1' if link['enabled'] else '0',
                          position='1' if link['position'] else '0', positionOffset=numbers(link['position_offset']),
                          rotation='1' if link['rotation'] else '0', rotationOffset=numbers(link['rotation_offset']),
                          scale='1' if link['scale'] else '0', scaleOffset=numbers(link['scale_offset']))

    # Timeline rows
    timeline = ET.fromstring(extended['timeline'][1]['sceneInfo'])
    rows = ET.SubElement(template, 'rows')
    body_shapes = {}

    def copy_rows(source, target):
        for node in source:
            if node.tag == 'interpolableGroup':
                group = ET.Element('interpolableGroup', name=node.get('name'))
                copy_rows(node, group)
                if len(group):
                    target.append(group)
                continue
            if node.tag != 'interpolable':
                continue
            key = order[int(node.get('objectIndex'))]
            a = node.attrib
            row = {'owner': a['owner'], 'id': a['id'],
                   'color': numbers((float(a.get('bgColorR', 1)), float(a.get('bgColorG', 1)), float(a.get('bgColorB', 1))), 6)}
            if key == character['key']:
                path = a.get('guideObjectPath') or a.get('parameter') or a.get('parameter1') or ''
                leaf = path.rsplit('/', 1)[-1]
                if a['id'] == 'lastBlendShape' and leaf == BODY_RENDERER:
                    index = int(a['parameter2'])
                    if id(target) not in body_shapes:
                        body_shapes[id(target)] = ET.SubElement(target, 'interpolable', owner='KKPE', id='lastBlendShape',
                                                               renderer=BODY_RENDERER, eachShape='', color=row['color'])
                    entry = body_shapes[id(target)]
                    entry.set('eachShape', (entry.get('eachShape') + ' ' + str(index)).strip())
                    continue
                row['bone' if a['id'] != 'lastBlendShape' and 'BlendShape' not in a['id'] else 'renderer'] = leaf
                if 'parameter2' in a:
                    row['index'] = a['parameter2']
            elif key in setup_keys:
                row['object'] = 'k%d' % key
                for name in ('materialName', 'propertyName', 'rendererName'):
                    if name in a:
                        row[name] = a[name]
            else:
                continue
            ET.SubElement(target, 'interpolable', **row)

    copy_rows(timeline, rows)
    ET.indent(template, '  ')
    args.output.write_text('<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(template, encoding='unicode') + '\n', encoding='utf-8')
    count = len(template.findall('.//interpolable'))
    print('%s: %d objects, %d constraints, %d row entries' % (args.output.name, len(setup_keys), len(template.findall('constraint')), count))


if __name__ == '__main__':
    main()
