param(
    [Parameter(Mandatory = $true)]
    [string] $GamePath,

    [ValidateSet('All', 'Timeline', 'Advanced', 'Pad')]
    [string] $Target = 'All',

    # Private: the author's own build, with Char Setup (Timeline\bin).
    # Public:  the build for distribution, without Char Setup (Timeline\bin\public).
    # Only the Timeline plugin differs; Advanced and Pad are built once.
    [ValidateSet('Both', 'Private', 'Public')]
    [string] $Edition = 'Both'
)

$ErrorActionPreference = 'Stop'
$compiler = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v3.5\csc.exe'
$framework = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v2.0.50727'

$referenceFiles = @(
    'BepInEx\core\BepInEx.dll'
    'BepInEx\core\0Harmony.dll'
    'CharaStudio_Data\Managed\UnityEngine.dll'
    'CharaStudio_Data\Managed\UnityEngine.UI.dll'
    'CharaStudio_Data\Managed\Assembly-CSharp.dll'
    'CharaStudio_Data\Managed\Assembly-CSharp-firstpass.dll'
)

$references = $referenceFiles | ForEach-Object { Join-Path $GamePath $_ }
foreach ($path in $references) {
    if (!(Test-Path -LiteralPath $path)) {
        throw "Missing local reference: $path"
    }
}

# Char Setup: left out of the Public edition, because it crashes the game on some installations.
$charSetupSources = @(
    'CharacterSetup.cs'
    'SetupObjects.cs'
    'SetupThemes.cs'
    'WorkflowVerification.cs'   # its checks all start from Char Setup rows
)

$filenames = @{
    Timeline = 'GIN Timeline life hack.dll'
    Advanced = 'GIN Advance mode life hack.dll'
    Pad      = 'GIN Pad life hack.dll'
}

foreach ($part in @('Timeline', 'Advanced', 'Pad')) {
    if ($Target -ne 'All' -and $Target -ne $part) {
        continue
    }

    $project = Join-Path $PSScriptRoot $part
    $filename = $filenames[$part]
    $editions = @('Private')
    if ($part -eq 'Timeline') {
        $editions = @('Private', 'Public') | Where-Object { $Edition -eq 'Both' -or $Edition -eq $_ }
    }

    foreach ($build in $editions) {
        $charSetup = $part -eq 'Timeline' -and $build -eq 'Private'
        $output = Join-Path $project 'bin'
        if ($build -eq 'Public') {
            $output = Join-Path $output 'public'
        }

        New-Item -ItemType Directory -Force -Path $output | Out-Null

        $arguments = @(
            '/noconfig'
            '/nologo'
            '/target:library'
            '/optimize+'
            '/debug-'
            ('/out:' + (Join-Path $output $filename))
            ('/reference:' + (Join-Path $framework 'System.dll'))
            ('/reference:' + (Join-Path $framework 'System.Xml.dll'))
            ('/reference:' + (Join-Path $GamePath 'CharaStudio_Data\Managed\System.Core.dll'))
        )
        $arguments += $references | ForEach-Object { '/reference:' + $_ }

        if ($part -eq 'Timeline') {
            $arguments += '/reference:' + (Join-Path $GamePath 'BepInEx\plugins\Timeline.dll')
        }

        if ($charSetup) {
            $arguments += '/define:CHAR_SETUP'
            # The Char Setup template (generated by tools/extract_character_setup.py) travels inside the DLL.
            $arguments += '/resource:' + (Join-Path $project 'CharacterSetup.xml') + ',CharacterSetup.xml'
        }

        if ($part -eq 'Pad') {
            # The 32x32 toolbar icon travels inside the DLL.
            $arguments += '/resource:' + (Join-Path $project 'ToolbarIcon.png') + ',ToolbarIcon.png'
        }

        $arguments += Get-ChildItem -LiteralPath $project -Filter '*.cs' -File -Recurse |
            Where-Object { $_.FullName -notmatch '[\\/]bin[\\/]' } |
            Where-Object { $charSetup -or $part -ne 'Timeline' -or $charSetupSources -notcontains $_.Name } |
            ForEach-Object FullName

        # Shared code (endless drags) that a plugin carries its own copy of.
        if ($part -ne 'Timeline') {
            $arguments += Get-ChildItem -LiteralPath (Join-Path $PSScriptRoot 'Shared') -Filter '*.cs' -File |
                ForEach-Object FullName
        }

        & $compiler $arguments
        if ($LASTEXITCODE -ne 0) {
            throw "$part ($build) compilation failed"
        }

        Get-FileHash -LiteralPath (Join-Path $output $filename) -Algorithm SHA256
    }
}
